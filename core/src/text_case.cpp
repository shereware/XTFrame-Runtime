uint32_t toUpper(uint32_t cp) { return cp < kTableSize ? kUpper[cp] : cp; }

uint32_t toLower(uint32_t cp) { return cp < kTableSize ? kLower[cp] : cp; }

bool isWordSeparator(uint32_t cp) {
    if (cp < 0x80) {
        const bool space = cp == 0x20 || (cp >= 0x09 && cp <= 0x0D);
        const bool punct = (cp >= 0x21 && cp <= 0x2F) || (cp >= 0x3A && cp <= 0x40) ||
                           (cp >= 0x5B && cp <= 0x60) || (cp >= 0x7B && cp <= 0x7E);
        return space || punct;
    }
    // The rest of Unicode White_Space (PropList.txt).
    return cp == 0x85 || cp == 0xA0 || cp == 0x1680 || (cp >= 0x2000 && cp <= 0x200A) || cp == 0x2028 ||
           cp == 0x2029 || cp == 0x202F || cp == 0x205F || cp == 0x3000;
}

void apply(std::string_view text, TextTransform transform, std::string& out) {
    out.assign(text.data(), text.size());
    if (transform == TextTransform::None) {
        return;
    }
    bool wordStart = true;
    size_t at = 0;
    while (at < text.size()) {
        uint32_t cp = 0;
        const size_t length = decode(text, at, cp);
        uint32_t mapped = cp;
        switch (transform) {
            case TextTransform::Uppercase:
                mapped = toUpper(cp);
                break;
            case TextTransform::Lowercase:
                mapped = toLower(cp);
                break;
            case TextTransform::Capitalize:
                mapped = wordStart ? toUpper(cp) : cp;
                wordStart = isWordSeparator(cp);
                break;
            case TextTransform::None:
                break;
        }
        if (mapped != cp) {
            encodeOver(out, at, length, mapped);
        }
        at += length;
    }
    // T-323 item 3: every mapping keeps the UTF-8 length, so run offsets never move.
    XT_ASSERT(out.size() == text.size());
}

