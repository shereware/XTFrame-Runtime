/// Decodes the code point at `text[at]`; returns its byte length (1 for a malformed byte, whose
/// `cp` is then U+FFFD).
size_t decode(std::string_view text, size_t at, uint32_t& cp) {
    const auto byte = [&text](size_t i) { return static_cast<uint8_t>(text[i]); };
    const uint8_t lead = byte(at);
    size_t length = 0;
    uint32_t min = 0;
    if (lead < 0x80) {
        cp = lead;
        return 1;
    }
    if (lead >= 0xC2 && lead <= 0xDF) {
        length = 2;
        cp = lead & 0x1Fu;
        min = 0x80;
    } else if (lead >= 0xE0 && lead <= 0xEF) {
        length = 3;
        cp = lead & 0x0Fu;
        min = 0x800;
    } else if (lead >= 0xF0 && lead <= 0xF4) {
        length = 4;
        cp = lead & 0x07u;
        min = 0x10000;
    } else {
        cp = 0xFFFD;
        return 1;
    }
    if (at + length > text.size()) {
        cp = 0xFFFD;
        return 1;
    }
    for (size_t i = 1; i < length; ++i) {
        const uint8_t next = byte(at + i);
        if ((next & 0xC0u) != 0x80u) {
            cp = 0xFFFD;
            return 1;
        }
        cp = (cp << 6) | (next & 0x3Fu);
    }
    if (cp < min || cp > 0x10FFFF || (cp >= 0xD800 && cp <= 0xDFFF)) {
        cp = 0xFFFD;
        return 1;
    }
    return length;
}

/// Writes the mapped code point `cp` over the `length` bytes at `out[at]`. The tables only map a
/// one-byte code point to a one-byte one and a two-byte one to a two-byte one.
void encodeOver(std::string& out, size_t at, size_t length, uint32_t cp) {
    if (length == 1) {
        XT_ASSERT(cp < 0x80);
        out[at] = static_cast<char>(cp);
        return;
    }
    XT_ASSERT(length == 2 && cp >= 0x80 && cp < 0x800);
    out[at] = static_cast<char>(0xC0u | (cp >> 6));
    out[at + 1] = static_cast<char>(0x80u | (cp & 0x3Fu));
}

