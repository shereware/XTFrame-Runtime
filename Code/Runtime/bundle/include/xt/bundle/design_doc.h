/// The authoritative design document `design/DESIGN.md`, the audit of the existing design and the
/// remaining design lint (Docs/design/35-design-system.md §35.4, §35.7.1 `design.build` /
/// `design.audit` / `design.lint`, §35.10, §35.16; Docs/tasks/T-309.md items 1, 3, 4).
///
/// The document is generated, never edited: fixed section order (`design.yaml:sections` lists the
/// sections to show; it cannot reorder them), fixed table columns, no timestamps, LF only, so the
/// same sources always give the same bytes. It uses only the note subset of §35.16 (headings 1-3,
/// paragraphs, emphasis, inline code, links, images, lists, quotes, code blocks, tables, rules).

namespace xt::bundle::design {

/// The first line of every generated document (§35.4).
inline constexpr std::string_view kDesignDocBanner =
    "<!-- generated by xtframe-design from design/, shared/ and conventions/; edit those, not this file -->";

/// The section keys, in document order (sections 1..13; 14 is reserved and never written). A text
/// entry's front matter `section` uses the same keys.
inline constexpr std::string_view kDesignSectionKeys[] = {
    "identity",   "voice",   "color",   "type",      "space",     "motion", "layout",
    "components", "imagery", "screens", "decisions", "changelog", "assets"};

struct BuildOptions {
    /// The AI version: no images, no Deprecated subsections, each section cut to its share of
    /// maxTokensHint (4 characters = 1 token) with a `… (N more)` line.
    bool forAi = false;
    int maxTokensHint = 20000;
    /// Only these sections (keys of kDesignSectionKeys or their numbers "1".."13"); empty = all.
    /// Applied after `design.yaml:sections`.
    std::vector<std::string> sections;
    /// T-309 addition: the standard symbol group (the directory holding its `index.json`) for the
    /// Components section; empty = the section lists only the project's symbols. T-498c (49 §49.12
    /// ruling): also the implied default layer -- its `tokens.xts` and theme files give the
    /// `### Inherited from <group id>` table after each Variables table (the group's tokens the
    /// project does not declare), and resolve an inherited variable in the contrast table and the
    /// lint; empty = no inherited variables.
    std::string standardSymbolDir;
};

/// Generates the document of `ds` in `project` (`graph` = buildGraph() of the two). The variables
/// come from `shared.tokens` (metadata from `ds`, synced as syncTokenMeta() would), the theme
/// columns from `shared.themes/*.xts`. `issues` (may be null) receives the lint of the result:
/// syncTokenMeta()'s findings, validate() and lintDocument() without `design.docStale`.
/// kInvalidArgument for an unnamed project.
Status buildDocument(const UiProject& project, const DesignSystem& ds, const Graph& graph,
                     const BuildOptions& options, std::string& markdown, std::vector<Issue>* issues);

/// buildDocument() with `forAi` and `sections` ignored (the full document), written to
/// `<design dir>/DESIGN.md` (only when its bytes differ). kIoError when it cannot be written.
Status writeDocument(const UiProject& project, const DesignSystem& ds, const Graph& graph,
                     const BuildOptions& options, std::vector<Issue>* issues, std::string* error = nullptr);

/// What audit() found (§35.7.1 `design.audit`).
struct AuditReport {
    /// One literal value: how often it occurs and where (`<ui>#<layer>`, or the file relative to
    /// the project root), sorted and unique. Colours also get the nearest swatch (by ΔE2000) and
    /// that ΔE; sizes and fonts leave them empty / 0.
    struct Literal {
        std::string value;
        int count = 0;
        std::vector<std::string> where;
        std::string nearestSwatch;
        float deltaE = 0.0f;
    };
    /// Colours (`#hex`, `rgb()`/`rgba()`, as lowercase `#rrggbb[aa]`), lengths (`<n>px`) and
    /// `font-family` values; each list sorted by count (largest first), then value.
    std::vector<Literal> colors, sizes, fonts;
    /// var() uses of colour / length variables ÷ (those + literal colours + literal lengths); 0 when
    /// there are none.
    float tokenCoverage = 0.0f;
    /// Literal colour pairs with ΔE2000 < 3, each pair sorted, the list sorted.
    std::vector<std::pair<std::string, std::string>> nearDuplicates;
};

/// Scans the style values of `scope` (`uis`: every UI document's `style=` attributes and `<style>`
/// blocks, the `.xts` files it links and `shared.styles`; `symbols`: every `.xt` under
/// `shared.symbols`; `all`: both). Custom property declarations (`--name: ...`) are definitions and
/// are skipped. kInvalidArgument for an unknown scope or an unnamed project.
Status audit(const UiProject& project, const DesignSystem& ds, std::string_view scope, AuditReport& out);

/// The §35.10 checks that need the project files: design.literalColorNotInPalette (info: a UI
/// literal colour with ΔE2000 > 2 to every swatch; nothing when the palette has no colour),
/// design.contrastLow (warning: a `palette.yaml:contrast` pair below its `min`, base and each
/// theme), design.draftShipped (warning: a draft variable), asset.placeholderShipped (T-312a, error:
/// an asset with status `placeholder`, assets::assetHygiene(); `entry` is its project-relative path)
/// design.docStale (info: `DESIGN.md` missing or different from buildDocument() with `options`,
/// forAi and sections ignored) and token.sameAsDefault (T-498b, warning: a `shared.tokens`
/// declaration whose value is exactly what the group at `options.standardSymbolDir` declares in its
/// `tokens.xts`; `entry` is the token).
std::vector<Issue> lintDocument(const UiProject& project, const DesignSystem& ds, const Graph& graph,
                                const BuildOptions& options = BuildOptions());

}  // namespace xt::bundle::design
