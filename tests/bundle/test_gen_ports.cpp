constexpr const char* kPortsDoc =
    R"X(<xt><body><div id="Hud" port:hp="number in" port:rarity="enum(common|rare) out"
    port:items="list<struct{name: string, count: number}>" port:stats="struct{hits: number, alive: bool}"
    port:hit="event out"></div></body></xt>)X";

std::unique_ptr<Document> documentOf(const std::string& text) {
    const compile::SourceFile file{"hud.xt", text};
    compile::CompileOptions options;
    compile::CompileResult result = compile::compileDocumentFromStrings({&file, 1}, "hud.xt", options);
    for (const compile::Diagnostic& d : result.diagnostics) {
        CAPTURE(d.message);
        CHECK(d.level != compile::Diagnostic::Level::Error);
    }
    REQUIRE(result.ok());
    static NullTextShaper shaper;
    std::unique_ptr<Document> doc;
    REQUIRE(Document::load(IrBlob{result.ir.data(), result.ir.size()}, true, &shaper, nullptr, doc) ==
            Status::kOk);
    return doc;
}

/// T-408: a UI with ports, a `@timeline` and custom states.
std::string contractDoc(const char* hpType) {
    return std::string(R"X(<xt><head><style>
      #Bar { width: 10px; }
      @timeline intro { #Bar { 0s { width: 0px } 1s { width: 10px } } }
    </style></head><body><div id="Hud" port:hp=")X") +
           hpType + R"X( in" port:rarity="enum(common|rare) out" port:hit="event out"
      state-groups="Level: Low|Ok"><div id="Bar"></div></div></body></xt>)X";
}

std::vector<PortRecord> portsOf(const char* text) {
    const compile::SourceFile file{"hud.xt", text};
    compile::CompileOptions options;
    compile::CompileResult result = compile::compileDocumentFromStrings({&file, 1}, "hud.xt", options);
    for (const compile::Diagnostic& d : result.diagnostics) {
        CAPTURE(d.message);
        CHECK(d.level != compile::Diagnostic::Level::Error);
    }
    REQUIRE(result.ok());
    NullTextShaper shaper;
    std::unique_ptr<Document> doc;
    REQUIRE(Document::load(IrBlob{result.ir.data(), result.ir.size()}, true, &shaper, nullptr, doc) ==
            Status::kOk);
    return doc->ports();
}

constexpr const char* kExpectedCpp =
    R"(// Generated by `xtframe-pack --gen-ports cpp` from the bundle's declared ports. Do not edit.
// The PortId values belong to this build's .xtir files; Document::lookupPort() resolves the
// same names at run time.
#pragma once

#include <array>
#include <cstdint>
#include <string>

namespace xtui {

using PortId = std::uint32_t;

namespace hud_main {

enum class Rarity : std::uint32_t { common = 0, rare = 1 };

struct Item {
    std::string name;
    float count = 0;
};

struct Stats {
    float hits = 0;
    bool alive = false;
};

constexpr PortId hp = 1;  // number, in
constexpr PortId rarity = 2;  // enum, out (Rarity)
constexpr PortId items = 3;  // list, in (list<Item>)
constexpr PortId stats = 4;  // struct, in (Stats)
constexpr PortId hit = 5;  // event, out

}  // namespace hud_main

}  // namespace xtui
)";

constexpr const char* kExpectedCs = R"(// <auto-generated>
// Generated by `xtframe-pack --gen-ports cs` from the bundle's declared ports. Do not edit.
// The port ids belong to this build's .xtir files; Document::lookupPort() resolves the same
// names at run time.
// </auto-generated>

namespace Xtui.HudMain
{
    public enum Rarity : uint
    {
        Common = 0,
        Rare = 1,
    }

    public struct Item
    {
        public string Name;
        public float Count;
    }

    public struct Stats
    {
        public float Hits;
        public bool Alive;
    }

    public static class Ports
    {
        /// <summary>number, in</summary>
        public const uint Hp = 1;
        /// <summary>enum, out (Rarity)</summary>
        public const uint Rarity = 2;
        /// <summary>list, in (Item[])</summary>
        public const uint Items = 3;
        /// <summary>struct, in (Stats)</summary>
        public const uint Stats = 4;
        /// <summary>event, out</summary>
        public const uint Hit = 5;
    }
}
)";

std::string readText(const fs::path& path) {
    std::ifstream in(path, std::ios::binary);
    std::stringstream buffer;
    buffer << in.rdbuf();
    return buffer.str();
}

void writeText(const fs::path& path, const std::string& text) {
    std::ofstream out(path, std::ios::binary);
    out << text;
}

std::string copiedSample(const std::string& name) {
    const fs::path dir = xt::test::tempDir() / ("xt_t193_src_" + name);
    std::error_code ec;
    fs::remove_all(dir, ec);
    fs::copy(fs::path(XT_TEST_BUNDLE_DIR) / "fixtures" / "sample", dir, fs::copy_options::recursive, ec);
    REQUIRE(ec.value() == 0);
    return dir.generic_string();
}

std::string outDir(const std::string& name) {
    const fs::path dir = xt::test::tempDir() / ("xt_t193_out_" + name);
    std::error_code ec;
    fs::remove_all(dir, ec);
    return dir.generic_string();
}

